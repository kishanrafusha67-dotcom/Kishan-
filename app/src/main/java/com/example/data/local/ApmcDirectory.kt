    fun findByNumber(number: String): ApmcShop? {
        val trimmed = number.trim()
        if (trimmed.isEmpty()) return null
        return shops.firstOrNull { it.shopNumber.equals(trimmed, ignoreCase = true) }
            ?: shops.firstOrNull { it.shopNumber.startsWith(trimmed, ignoreCase = true) }
    }

    fun search(query: String): List<ApmcShop> {
        val q = query.trim().lowercase()
        if (q.isEmpty()) return shops
        return shops.filter {
            it.shopNumber.lowercase().contains(q) ||
            it.name.lowercase().contains(q) ||
            it.mobile.contains(q)
        }
    }
